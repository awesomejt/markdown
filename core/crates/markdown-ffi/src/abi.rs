//! `#[repr(C)]` mirrors of `core/include/markdown_core.h`. Field order, types
//! and constant values must match the header exactly; `tests/c_abi.rs`
//! compares sizes and offsets with the C compiler's view.
#![allow(non_camel_case_types)]

