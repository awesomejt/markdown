pub type md_snapshot = u64;

/// Define ABI constants and a `(name, value)` table of all of them.
macro_rules! constants {
    ($($name:ident: $ty:ty = $value:expr;)+) => {
        $(pub const $name: $ty = $value;)+
        /// Every constant in `markdown_core.h`, for header drift checks.
        pub const CONSTANTS: &[(&str, u64)] = &[$((stringify!($name), $name as u64)),+];
    };
}

